import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROW = re.compile(r'^GP\("([^"]+)", "([^"]+)", (\w+), "([^"]+)", (true|false), ([-\d.e]+), ([-\d.e]+), ([-\d.e]+), ([-\d.e]+), ([-\d.e]+), ([-\d.e]+), "([^"]*)", "([^"]*)"\)')

def rows(name):
    out = []
    for line in open(os.path.join(ROOT, "src/gate", name)):
        m = ROW.match(line.strip())
        if m: out.append(m.groups())
    return out

TARGET = {"PHYS": "BallPhysics", "FEEL": "PlayerFeel", "EXT": "goofy"}
def num(x):
    v = float(x)
    return str(int(v)) if v == int(v) and abs(v) < 1e15 else ("%g" % v)


def visual(sec, col): return col == "true" or sec == "visuals"
def sync_class(sec, col): return "visual (own)" if visual(sec, col) else "host"

def table(rs):
    t = ["| id | target | default | min | max | unit | apply | sync |", "|---|---|---|---|---|---|---|---|"]
    for (i, sec, tgt, prop, col, d0, d1, d2, d3, lo, hi, unit, apply) in rs:
        d = "[%s, %s, %s, %s]" % (num(d0), num(d1), num(d2), num(d3)) if col == "true" else num(d0)
        t.append(f"| `{i}` | {TARGET[tgt]} | {d} | {num(lo)} | {num(hi)} | {unit} | {apply} | {sync_class(sec, col)} |")
    return t

def sections(rs, order, titles):
    out = []
    for s in order:
        sub = [r for r in rs if r[1] == s]
        if not sub: continue
        out += [f"### {titles.get(s, s)} ({len(sub)})", ""] + table(sub) + [""]
    left = sorted(set(r[1] for r in rs) - set(order))
    assert not left, left
    return out

