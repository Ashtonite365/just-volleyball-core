#!/usr/bin/env python3
"""Inventory what the game itself exposes, for the mod API (docs/GAME_SURFACE.md).

Reads the recovered game scripts (box only, never shipped or published):
    tools/gen_game_surface.py <game-scripts-folder> > docs/GAME_SURFACE.md
Lists names and file:line only (no game code is copied): autoload singletons, input
actions, every class_name, signal, @rpc function and exported/config variable.
"""
import os, re, sys
from collections import defaultdict

root = sys.argv[1] if len(sys.argv) > 1 else None
if not root:
    sys.exit("usage: gen_game_surface.py <game-scripts-folder>")
proj = open(os.path.join(root, "project.godot"), encoding="utf-8", errors="replace").read().splitlines()

def section(name):
    out, on = [], False
    for i, l in enumerate(proj, 1):
        if l.startswith("["):
            on = l.strip() == "[%s]" % name
            continue
        if on and l.strip():
            out.append((i, l))
    return out

autoloads = [(i, l.split("=", 1)[0], l.split("=", 1)[1].strip('"*')) for i, l in section("autoload") if "=" in l]
actions = [(i, l.split("=", 1)[0]) for i, l in section("input") if re.match(r"^[a-z_0-9]+=\{", l)]
globals_ = [(i, l.split("=", 1)[0]) for i, l in section("shader_globals") if re.match(r"^[a-z_0-9]+=\{", l)]

files = []
for d, _, fs in os.walk(os.path.join(root, "game")):
    for f in fs:
        if f.endswith(".gd"):
            files.append(os.path.relpath(os.path.join(d, f), root))
files.sort()

cls, sigs, rpcs, exports = {}, defaultdict(list), defaultdict(list), defaultdict(list)
for f in files:
    lines = open(os.path.join(root, f), encoding="utf-8", errors="replace").read().splitlines()
    pending_rpc = None
    for n, l in enumerate(lines, 1):
        m = re.match(r"^class_name\s+(\w+)", l)
        if m: cls[f] = (n, m.group(1))
        m = re.match(r"^signal\s+(\w+)(\(.*\))?", l)
        if m: sigs[f].append((n, m.group(1) + (m.group(2) or "")))
        if l.startswith("@rpc"):
            pending_rpc = (n, l.strip())
            m = re.search(r"func\s+(\w+)", l)
            if m: rpcs[f].append((n, m.group(1), l.split("func")[0].strip())); pending_rpc = None
            continue
        if pending_rpc:
            m = re.match(r"^\s*(static\s+)?func\s+(\w+)", l)
            if m: rpcs[f].append((pending_rpc[0], m.group(2), pending_rpc[1])); pending_rpc = None
            elif l.strip() and not l.startswith("@"): pending_rpc = None
        m = re.match(r"^@export\w*(\([^)]*\))?\s+var\s+(\w+)", l)
        if m: exports[f].append((n, m.group(2)))

w = sys.stdout.write
w("# Game surface reachable by the mod API (generated)\n\n")
w("Generated by `tools/gen_game_surface.py` from the recovered scripts of build 26827091 "
  "(names and file:line only, no game code). Paths are relative to `res://`.\n")
w("Do not edit by hand; regenerate after a game update and re-run `tools/check_api_refs.py`.\n\n")
w("| item | count |\n|---|---|\n")
w("| autoload singletons | %d |\n| input actions | %d |\n| shader globals | %d |\n| scripts (game/) | %d |\n| class_name types | %d |\n| signals | %d |\n| @rpc functions | %d |\n| @export variables | %d |\n\n" % (
    len(autoloads), len(actions), len(globals_), len(files), len(cls), sum(map(len, sigs.values())), sum(map(len, rpcs.values())), sum(map(len, exports.values()))))
w("## Autoload singletons (project.godot)\n\n| name | script | line |\n|---|---|---|\n")
for i, n, p in autoloads: w("| `%s` | `%s` | project.godot:%d |\n" % (n, p.replace("res://", ""), i))
w("\n## Input actions (project.godot [input])\n\n")
w(", ".join("`%s` (%d)" % (a, i) for i, a in actions) + "\n\n")
w("## Global shader uniforms (project.godot [shader_globals])\n\n" + ", ".join("`%s` (%d)" % (a, i) for i, a in globals_) + "\n\n")
w("## Classes, signals and RPCs per script\n\n")
for f in files:
    if f not in cls and f not in sigs and f not in rpcs: continue
    head = "`%s`" % f + (" - class_name `%s` (:%d)" % (cls[f][1], cls[f][0]) if f in cls else "")
    w("### %s\n\n" % head)
    if sigs[f]: w("- signals: " + "; ".join("`%s` :%d" % (s, n) for n, s in sigs[f]) + "\n")
    if rpcs[f]: w("- rpc: " + "; ".join("`%s` :%d `%s`" % (s, n, a) for n, s, a in rpcs[f]) + "\n")
    if exports[f]: w("- exported: " + ", ".join("`%s` :%d" % (s, n) for n, s in exports[f][:60]) + (" (+%d more)" % (len(exports[f]) - 60) if len(exports[f]) > 60 else "") + "\n")
    w("\n")
others = [f for f in files if f not in cls and f not in sigs and f not in rpcs]
w("## Scripts without class_name, signals or RPCs\n\n" + ", ".join("`%s`" % f for f in others) + "\n")
