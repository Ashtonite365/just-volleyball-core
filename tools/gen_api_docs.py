#!/usr/bin/env python3
"""Regenerate the capability tables in docs/API.md and rules.md from src/api/capabilities.def.
Replaces the text between <!-- caps:begin --> and <!-- caps:end --> in each file.
    tools/gen_api_docs.py
"""
import os, re

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.join(here, "..")
src = open(os.path.join(repo, "src/api/capabilities.def")).read()
caps = []
for m in re.finditer(r'^JV_CAP\((.*)\)\s*$', src, re.M):
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"|([A-Z_]+)', m.group(1))
    vals = [a if a or not b else b for a, b in parts]
    caps.append(dict(zip(["id", "since", "access", "scope", "status", "feature", "refs", "fns"], vals)))

RULE = {
    "READ": "any mode once the version pin matched",
    "LOCAL_UI": "any mode once pinned (our own UI/files only)",
    "COSMETIC": "every identified mode incl. public/quick match (local only); off when unknown",
    "GAMEPLAY": "Free Play, practice, offline solo, menu, LAN, private, friends",
    "SYNC": "LAN, private, friends only",
    "OFFLINE": "Free Play, practice, offline solo, menu only",
}

def refs(r):
    return "-" if r == "-" else "<br>".join("`%s`" % x for x in r.split("; "))

def api_table():
    out = ["| capability | API functions | game feature | game refs (res://, build 26827091) | access | scope | status |", "|---|---|---|---|---|---|---|"]
    for c in caps:
        out.append("| `%s` | %s | %s | %s | %s | %s | %s |" % (c["id"], c["fns"], c["feature"], refs(c["refs"]), c["access"].lower(), c["scope"].lower(), c["status"].lower()))
    return "\n".join(out)

def rules_table():
    out = ["| capability | links to (game feature) | access class | allowed in | scope | status |", "|---|---|---|---|---|---|"]
    for c in caps:
        out.append("| `%s` | %s | %s | %s | %s | %s |" % (c["id"], c["feature"], c["access"].lower(), RULE[c["access"]], c["scope"].lower(), c["status"].lower()))
    return "\n".join(out)

def stats():
    n = len(caps)
    by = lambda k, v: sum(1 for c in caps if c[k] == v)
    nrefs = sum(0 if c["refs"] == "-" else len(c["refs"].split("; ")) for c in caps)
    return n, by("status", "IMPL"), by("status", "MAPPED"), by("status", "PLANNED"), nrefs

for fname, table in (("docs/API.md", api_table), ("rules.md", rules_table)):
    p = os.path.join(repo, fname)
    t = open(p).read()
    n, i, mp, pl, nr = stats()
    body = "<!-- caps:begin (generated by tools/gen_api_docs.py from src/api/capabilities.def; do not edit) -->\n%d capabilities: %d impl, %d mapped, %d planned; %d game file:line refs.\n\n%s\n<!-- caps:end -->" % (n, i, mp, pl, nr, table())
    t2 = re.sub(r"<!-- caps:begin.*?<!-- caps:end -->", lambda m: body, t, flags=re.S)
    open(p, "w").write(t2)
    print(fname, "updated" if t2 != t else "unchanged")
